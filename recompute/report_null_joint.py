def _f(x, nd=4):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "--"
    return f"{x:.{nd}f}"


def _p(row, prefix=""):
    """Render a p-value, honouring the 1/(B+1) floor."""
    rep = row.get(f"{prefix}p_report")
    if rep is None or (isinstance(rep, float) and pd.isna(rep)):
        return "--"
    return str(rep)


def _md_table(headers: List[str], rows: List[List[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join(["---"] * len(headers)) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(x) for x in r) + " |")
    return "\n".join(out)


def build() -> str:
    comp = pd.read_csv(RESULTS / "null_comparison_joint.csv")
    sweep = pd.read_csv(RESULTS / "null_sweep_mmin.csv")
    comb = pd.read_csv(RESULTS / "null_joint_combined.csv")
