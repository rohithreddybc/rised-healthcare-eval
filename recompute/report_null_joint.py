    raw = {f.stem: json.loads(f.read_text(encoding="utf-8"))
           for f in IN_DIR.glob("*.json")}
    b = int(comp["n_reps"].max())

    def _and(names):
        n = [NICE.get(c, c) for c in names]
        if not n:
            return "none"
        if len(n) == 1:
            return n[0]
        return ", ".join(n[:-1]) + " and " + n[-1]

    est = comp[comp["new_p_value"].notna()]
    sig_old = list(est.loc[est["sig_old_raw"], "cohort"])
    sig_new = list(est.loc[est["sig_new_raw"], "cohort"])
    sig_new_holm = list(est.loc[est["sig_new_holm"], "cohort"])
    sig_new_bh = list(est.loc[est["sig_new_bh"], "cohort"])

