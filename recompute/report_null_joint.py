    cj = comb[(comb["scheme"] == "joint")]
    c_m30 = cj[cj["rule"] == "m30"].iloc[0]
    c_ev = cj[cj["rule"] == "ev10"].iloc[0]
    sg = sign[(sign["scheme"] == "joint") & (sign["rule"] == "m30")].iloc[0]
    ev_j = sweep[(sweep["scheme"] == "joint") & (sweep["rule"] == "ev10")
                 ].set_index("cohort")

